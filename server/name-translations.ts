export function getNameTranslations(searchTerm: string): string[] {
  const term = searchTerm.toLowerCase().trim();
  const translations = new Set<string>([term]);

  const maxVariations = term.length <= 2 ? 5 : term.length === 3 ? 8 : 15;
  let variationCount = 0;

  if (nameMap[term] && variationCount < maxVariations) {
    nameMap[term].forEach(t => {
      if (variationCount < maxVariations) {
        translations.add(t);
        variationCount++;
      }
    });
  }

  if (variationCount < maxVariations) {
    for (const key of Object.keys(nameMap)) {
      if (variationCount >= maxVariations) break;
      if (key.startsWith(term) && key !== term) {
        translations.add(key);
        variationCount++;
        for (const t of nameMap[key]) {
          if (variationCount >= maxVariations) break;
          translations.add(t);
          variationCount++;
        }
      }
    }
  }

  if (term.length >= 3 && variationCount < maxVariations) {
    for (const key of Object.keys(nameMap)) {
      if (variationCount >= maxVariations) break;
      if (key.includes(term) && !key.startsWith(term) && key !== term) {
        translations.add(key);
        variationCount++;
        for (const t of nameMap[key]) {
          if (variationCount >= maxVariations) break;
          translations.add(t);
          variationCount++;
        }
      }
    }
  }

  return Array.from(translations);
}

export function normalizeMarathiVowels(text: string): string {
  return text
    .replace(/ी/g, 'ि')
    .replace(/ू/g, 'ु')
    .replace(/ै/g, 'े')
    .replace(/ौ/g, 'ो')
    .replace(/ॅ/g, 'े')
    .replace(/ॉ/g, 'ो')
    .replace(/आ/g, 'अ')
    .replace(/ई/g, 'इ')
    .replace(/ऊ/g, 'उ')
    .replace(/ऐ/g, 'ए')
    .replace(/औ/g, 'ओ');
}
